const dictionaries: Record<Lang, Record<MessageKey, string>> = { zh, en };

let current: Lang = "zh";
const listeners = new Set<() => void>();

export function systemLang(): Lang {
	return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function setLang(lang: Lang): void {
	if (lang === current) return;
	current = lang;
	document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
	for (const listener of listeners) listener();
}

export function getLang(): Lang {
	return current;
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
	const template = dictionaries[current][key] ?? key;
	return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

/** Re-renders the calling component when the language changes. */
export function useLang(): Lang {
	return useSyncExternalStore(
		(listener) => {
			listeners.add(listener);
			return () => listeners.delete(listener);
		},
		() => current,
	);
}

export function formatNumber(n: number): string {
	return new Intl.NumberFormat(current === "zh" ? "zh-CN" : "en-US").format(n);
}

export function formatCost(n: number): string {
	return n < 0.01 && n > 0 ? "<0.01" : n.toFixed(2);
}

export function formatTime(ms: number): string {
	return new Intl.DateTimeFormat(current === "zh" ? "zh-CN" : "en-US", {
		hour: "2-digit",
		minute: "2-digit",
	}).format(ms);
}
