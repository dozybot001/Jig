// Writes android/DEPENDENCIES.md: every library that goes into the released app (the release runtime
// classpath in app/gradle.lockfile), with its version and the license its POM names. The POMs are
// read from Gradle's cache on this machine, so build the app once first:
//   node android/scripts/dependencies.ts
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const here = new URL("..", import.meta.url).pathname;
const cache = join(homedir(), ".gradle/caches/modules-2/files-2.1");

function pom(group: string, name: string, version: string): string | null {
	const folder = join(cache, group, name, version);
	if (!existsSync(folder)) return null;
	for (const hash of readdirSync(folder)) {
		const file = join(folder, hash, `${name}-${version}.pom`);
		if (existsSync(file)) return readFileSync(file, "utf8");
	}
	return null;
}

/** The licenses a POM names, or those of its parent POM when it names none. */
function licenses(group: string, name: string, version: string, depth = 0): string[] {
	const text = pom(group, name, version);
	if (!text) return [];
	const block = /<licenses>([\s\S]*?)<\/licenses>/.exec(text)?.[1];
	const names = [...(block ?? "").matchAll(/<name>([^<]+)<\/name>/g)].map((m) => (m[1] as string).trim());
	if (names.length > 0 || depth > 3) return names;
	const parent = /<parent>([\s\S]*?)<\/parent>/.exec(text)?.[1];
	if (!parent) return [];
	const field = (tag: string) => new RegExp(`<${tag}>([^<]+)</${tag}>`).exec(parent)?.[1]?.trim() ?? "";
	return licenses(field("groupId"), field("artifactId"), field("version"), depth + 1);
}

const rows = readFileSync(join(here, "app/gradle.lockfile"), "utf8")
	.split("\n")
	.filter((line) => line.includes("releaseRuntimeClasspath"))
	.map((line) => (line.split("=")[0] as string).split(":") as [string, string, string])
	.sort((a, b) => a.join(":").localeCompare(b.join(":")));

const lines = rows.map(([group, name, version]) => {
	const found = licenses(group, name, version);
	return `| ${group}:${name} | ${version} | ${found.length > 0 ? [...new Set(found)].join("; ") : "(not stated in the POM)"} |`;
});
writeFileSync(
	join(here, "DEPENDENCIES.md"),
	`# Jig for Android: third-party libraries

The ${rows.length} libraries on the released app's runtime classpath, from \`app/gradle.lockfile\`, with the license each
library's POM names. Generated by \`scripts/dependencies.ts\`; do not edit. Entries that end in \`-bom\`
only pin versions and carry no code.

| Library | Version | License |
| --- | --- | --- |
${lines.join("\n")}
`,
);
process.stdout.write(`${rows.length} libraries\n`);
