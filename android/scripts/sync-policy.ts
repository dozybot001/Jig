// Writes the app's copy of the privacy policy and terms (res/values*/policy.xml) from the one text
// in src/shared/policy.ts:
//   node android/scripts/sync-policy.ts
// PolicyTest fails when the copy and the source differ.
import { writeFileSync } from "node:fs";
import { POLICY, POLICY_VERSION } from "../../src/shared/policy.ts";

const escape = (text: string) =>
	text
		.replaceAll("\\", "\\\\")
		.replaceAll("&", "&amp;")
		.replaceAll("<", "&lt;")
		.replaceAll("'", "\\'")
		.replaceAll('"', '\\"')
		.replaceAll("@", "\\@")
		.replaceAll("?", "\\?");

const array = (name: string, items: readonly string[]) =>
	`    <string-array name="${name}">\n${items.map((item) => `        <item>${escape(item)}</item>`).join("\n")}\n    </string-array>`;

for (const [folder, texts] of [
	["values", POLICY.en],
	["values-zh-rCN", POLICY.zh],
] as const) {
	const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/scripts/sync-policy.ts from src/shared/policy.ts. Do not edit. -->
<resources>
${folder === "values" ? `    <string name="policy_version" translatable="false">${POLICY_VERSION}</string>\n` : ""}    <string name="policy_date">${escape(texts.date)}</string>
${array("policy_privacy", texts.privacy)}
${array("policy_terms", texts.terms)}
</resources>
`;
	writeFileSync(new URL(`../app/src/main/res/${folder}/policy.xml`, import.meta.url), xml);
}
